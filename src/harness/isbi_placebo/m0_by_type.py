"""Question-only floor M0 (no-image baseline) per template and per class of Kvasir (plan v2 §3, nΔ_nec).

Trains NOTHING. Aggregates the `correct` field of the existing M0 file --
TF-IDF over the question + logistic regression, generated by
`rescoring/m0/kvasir_question_only.py` (commit 3ba7d0e of the anonymized repository;
65.74 %, 7,086/10,779) with three decisions declared in its header: source =
clean training set (validation left out), scope = the 10,779 questions, scoring rule =
answer_matches(normalize_text(...)). The floor is identical in every condition that does not
change the question text, so the C0 file serves for T, P and S.

Reports the floor on the whole test set and on the evaluable subset of the inventory (F1):
the normalization headroom Acc(C0) - Acc(M0_type) is computed on the same slice
on which Δ_nec is measured.

Usage:
    python -m harness.isbi_placebo.m0_by_type         --m0 results/isbi_placebo/M0_question_only_KVASIR_C0.json         --swapmap data/swapmap.json --inventory results/isbi_placebo/inventory_kvasir_test_clean.json         --output-json results/isbi_placebo/m0_by_type_kvasir.json         --output-md docs/isbi/placebo/m0_by_type_kvasir.md
"""
from __future__ import annotations

import argparse
import collections
import hashlib
import json
from pathlib import Path


def _acc(rows: list[dict]) -> dict:
    n = len(rows)
    c = sum(bool(r["correct"]) for r in rows)
    return {"n": n, "n_correct": c, "accuracy": c / n if n else None}


def m0_by_type(m0_path: str, swapmap_path: str, inventory_path: str, dataset: str = "KVASIR") -> dict:
    m0 = json.loads(Path(m0_path).read_text())
    qid2q = {int(k): v["q"] for k, v in json.loads(Path(swapmap_path).read_text())[dataset]["qid"].items()}
    inv = {q["qid"]: q for q in json.loads(Path(inventory_path).read_text())["questions"]}
    rows = m0["predictions"]
    missing = [r["qid"] for r in rows if r["qid"] not in qid2q or r["qid"] not in inv]
    if missing:
        raise ValueError(f"{len(missing)} qid(s) do M0 sem pergunta no swapmap ou sem registro no inventario: {missing[:5]}")
    by_t_full, by_t_ev, by_c_full, by_c_ev = (collections.defaultdict(list) for _ in range(4))
    for r in rows:
        q, rec = qid2q[r["qid"]], inv[r["qid"]]
        by_t_full[q].append(r); by_c_full[rec["question_class"]].append(r)
        if rec["evaluable"]:
            by_t_ev[q].append(r); by_c_ev[rec["question_class"]].append(r)
    return {
        "source": {"m0_file": m0_path, "m0_sha256": hashlib.sha256(Path(m0_path).read_bytes()).hexdigest(),
                   "n_predictions": len(rows), "swapmap": swapmap_path, "inventory": inventory_path, "dataset": dataset},
        "overall": _acc(rows),
        "by_template": {"full": {k: _acc(v) for k, v in by_t_full.items()},
                        "evaluable": {k: _acc(v) for k, v in by_t_ev.items()}},
        "by_class": {"full": {k: _acc(v) for k, v in by_c_full.items()},
                     "evaluable": {k: _acc(v) for k, v in by_c_ev.items()}},
    }


def render_markdown(out: dict) -> str:
    o = out["overall"]
    L = [f"# Piso só-pergunta M0 por tipo — {out['source'].get('dataset', 'KVASIR')}", "",
         f"Fonte: `{out['source']['m0_file']}` (sha256 `{out['source']['m0_sha256'][:12]}…`), {o['n']} perguntas, "
         f"acurácia global {o['accuracy']:.4f} ({o['n_correct']}/{o['n']}). Agregação, não modelo novo.", "",
         "| classe | n (teste) | M0 (teste) | n (avaliáveis) | M0 (avaliáveis) |", "|---|---:|---:|---:|---:|"]
    for k in sorted(out["by_class"]["full"]):
        f, e = out["by_class"]["full"][k], out["by_class"]["evaluable"].get(k, {"n": 0, "accuracy": None})
        L.append(f"| {k} | {f['n']} | {f['accuracy']:.3f} | {e['n']} | {e['accuracy']:.3f} |" if e["n"] else
                 f"| {k} | {f['n']} | {f['accuracy']:.3f} | 0 | — |")
    L += ["", "| template | n (teste) | M0 (teste) | n (avaliáveis) | M0 (avaliáveis) |", "|---|---:|---:|---:|---:|"]
    for k, f in sorted(out["by_template"]["full"].items(), key=lambda kv: -kv[1]["n"]):
        e = out["by_template"]["evaluable"].get(k, {"n": 0, "accuracy": None})
        L.append(f"| {k} | {f['n']} | {f['accuracy']:.3f} | {e['n']} | {e['accuracy']:.3f} |" if e["n"] else
                 f"| {k} | {f['n']} | {f['accuracy']:.3f} | 0 | — |")
    return "\n".join(L) + "\n"


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--m0", required=True)
    ap.add_argument("--swapmap", required=True)
    ap.add_argument("--inventory", required=True)
    ap.add_argument("--dataset", default="KVASIR")
    ap.add_argument("--output-json", required=True)
    ap.add_argument("--output-md")
    a = ap.parse_args(argv)
    out = m0_by_type(a.m0, a.swapmap, a.inventory, a.dataset)
    Path(a.output_json).parent.mkdir(parents=True, exist_ok=True)
    Path(a.output_json).write_text(json.dumps(out, indent=1) + "\n")
    md = render_markdown(out)
    if a.output_md:
        Path(a.output_md).write_text(md)
    print(md)


if __name__ == "__main__":
    main()
