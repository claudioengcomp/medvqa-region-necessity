"""Adds Kvasir-VQA-x1 support to a clone of the upstream M3AE repository (zhjohnchan/M3AE, commit 14da377), which has no such
dataset. The two new modules, `m3ae/datasets/vqa_kvasir_dataset.py` and `m3ae/datamodules/vqa_kvasir_datamodule.py`, are generated by
reading the upstream VQA-RAD modules from the clone and changing the names (`VQAVQARAD` -> `VQAKVASIR`, `vqa_vqa_rad` -> `vqa_kvasir`);
no upstream code is stored in this file. The `__init__` files of `datasets`/`datamodules` receive the import and the registry entry
(same pattern as the other datasets); `config.py` receives the named config `task_finetune_vqa_kvasir` (copy of
`task_finetune_vqa_vqa_rad` with `vqa_label_size` computed from the real Kvasir vocabulary). `vit`/`tokenizer`/`image_size` of the named
config are overridden by the command-line arguments passed by `harness/run_finetune_m3ae.sh` / `harness/extract_predictions_m3ae.py`
(`clip16 text_roberta image_size=384`); `batch_size=64` and `max_epoch=15` are the values used in this work.

Note on the split: `VQAVQARADDataModule.setup()` builds `answer2id`/`id2answer` from `train_dataset` + `val_dataset` (never
`test_dataset`), so `vqa_kvasir_val.arrow` must exist before training (`harness/prepro/split_kvasir_train_val.py`).

Idempotent: each `write_*`/`patch_*` step checks whether the change is already present.
Usage (after cloning M3AE and building the vocabulary with harness/prepro/build_kvasir_answer_vocab.py):
    python -m harness.patch_m3ae_kvasir --m3ae-dir <M3AE clone> --vocab-json data/finetune_arrows/kvasir_answer_vocab.json
"""
from __future__ import annotations

import argparse
import json
import os

_UPSTREAM = {"dataset": "m3ae/datasets/vqa_vqa_rad_dataset.py", "datamodule": "m3ae/datamodules/vqa_vqa_rad_datamodule.py"}
_HEADER = ('"""VQA{U}{Kind}: copy of {rel} (zhjohnchan/M3AE, commit 14da377) with the names changed. '
           'Generated by {generator}; edit the generator, not this file."""\n')


def _from_upstream(m3ae_dir: str, rel: str, old: str, new: str, header: str) -> str:
    """Reads the upstream module `rel` from the M3AE clone and returns it with the dataset names changed
    (`VQA<OLD>` -> `VQA<NEW>`, `vqa_<old>` -> `vqa_<new>`), preceded by `header`. No upstream code is stored here."""
    with open(os.path.join(m3ae_dir, rel), "r", encoding="utf-8") as fp:
        src = fp.read()
    return header + src.replace(f"VQA{old.replace('_', '').upper()}", f"VQA{new.upper()}").replace(f"vqa_{old}", f"vqa_{new}")


def module_source(m3ae_dir: str, kind: str, name: str = "kvasir", generator: str = "harness/patch_m3ae_kvasir.py") -> str:
    """Source of the generated `vqa_<name>_<kind>.py` (`kind` in {"dataset", "datamodule"})."""
    rel = _UPSTREAM[kind]
    header = _HEADER.format(U=name.upper(), Kind="Dataset" if kind == "dataset" else "DataModule", rel=rel, generator=generator)
    return _from_upstream(m3ae_dir, rel, "vqa_rad", name, header)


_NAMED_CONFIG_TEMPLATE = '''@ex.named_config
def task_finetune_vqa_kvasir():
    exp_name = "task_finetune_vqa_kvasir"
    datasets = ["vqa_kvasir"]
    loss_names = _loss_names({{"vqa": 1}})
    batch_size = 64
    max_epoch = 15
    max_steps = None
    warmup_steps = 0.1
    draw_false_image = 0
    learning_rate = 5e-6
    val_check_interval = 1.0
    lr_multiplier_head = 50
    lr_multiplier_multi_modal = 5
    tokenizer = "bert-base-uncased"
    max_text_len = 32
    input_text_embed_size = 768
    vit = 'ViT-B/32'
    train_transform_keys = ["clip"]
    val_transform_keys = ["clip"]
    input_image_embed_size = 768
    image_size = 576

    vqa_label_size = {vqa_label_size}
'''

_DATASETS_IMPORT_LINE = "from .vqa_kvasir_dataset import VQAKVASIRDataset\n"
_DATAMODULES_IMPORT_LINE = "from .vqa_kvasir_datamodule import VQAKVASIRDataModule\n"
_DATAMODULES_MARKER = "\n_datamodules = {"
_DATAMODULES_ANCHOR_ENTRY = '"vqa_vqa_rad": VQAVQARADDataModule,'
_DATAMODULES_NEW_ENTRY = '"vqa_kvasir": VQAKVASIRDataModule,'


def write_dataset_file(m3ae_dir: str) -> str:
    path = os.path.join(m3ae_dir, "m3ae", "datasets", "vqa_kvasir_dataset.py")
    with open(path, "w", encoding="utf-8") as fp:
        fp.write(module_source(m3ae_dir, "dataset"))
    return path


def write_datamodule_file(m3ae_dir: str) -> str:
    path = os.path.join(m3ae_dir, "m3ae", "datamodules", "vqa_kvasir_datamodule.py")
    with open(path, "w", encoding="utf-8") as fp:
        fp.write(module_source(m3ae_dir, "datamodule"))
    return path


def patch_datasets_init(m3ae_dir: str) -> None:
    path = os.path.join(m3ae_dir, "m3ae", "datasets", "__init__.py")
    with open(path, "r", encoding="utf-8") as fp:
        content = fp.read()
    if "VQAKVASIRDataset" in content:
        return
    if content and not content.endswith("\n"):
        content += "\n"
    with open(path, "w", encoding="utf-8") as fp:
        fp.write(content + _DATASETS_IMPORT_LINE)


def patch_datamodules_init(m3ae_dir: str) -> None:
    """Inserts the import before the `_datamodules` dictionary and the new entry
    right after `"vqa_vqa_rad": VQAVQARADDataModule,` -- used as the anchor
    because VQA-RAD is the most recent and always present precedent. Raises
    ValueError if any marker does not match (a sign that the actual `__init__.py`
    changed format since this patch was written -- do not apply
    silently against a file we do not recognize)."""
    path = os.path.join(m3ae_dir, "m3ae", "datamodules", "__init__.py")
    with open(path, "r", encoding="utf-8") as fp:
        content = fp.read()
    if "VQAKVASIRDataModule" in content:
        return
    if _DATAMODULES_MARKER not in content:
        raise ValueError(f"{path}: marcador '_datamodules = {{' não encontrado — arquivo mudou de formato?")
    if _DATAMODULES_ANCHOR_ENTRY not in content:
        raise ValueError(f"{path}: entrada 'vqa_vqa_rad' não encontrada no dicionário — arquivo mudou de formato?")
    content = content.replace(_DATAMODULES_MARKER, f"\n{_DATAMODULES_IMPORT_LINE}{_DATAMODULES_MARKER}", 1)
    content = content.replace(
        _DATAMODULES_ANCHOR_ENTRY,
        f"{_DATAMODULES_ANCHOR_ENTRY}\n    {_DATAMODULES_NEW_ENTRY}",
        1,
    )
    with open(path, "w", encoding="utf-8") as fp:
        fp.write(content)


def patch_config(m3ae_dir: str, vqa_label_size: int) -> None:
    path = os.path.join(m3ae_dir, "m3ae", "config.py")
    with open(path, "r", encoding="utf-8") as fp:
        content = fp.read()
    if "def task_finetune_vqa_kvasir" in content:
        return
    if content and not content.endswith("\n"):
        content += "\n"
    new_config = _NAMED_CONFIG_TEMPLATE.format(vqa_label_size=vqa_label_size)
    with open(path, "w", encoding="utf-8") as fp:
        fp.write(content + "\n\n" + new_config)


def apply_patch(m3ae_dir: str, vocab_json_path: str) -> int:
    """Applies the full patch (2 new files + 3 edits) and returns the
    vqa_label_size used, for the caller to check/log."""
    with open(vocab_json_path, "r", encoding="utf-8") as fp:
        vocab = json.load(fp)
    vqa_label_size = len(vocab)

    write_dataset_file(m3ae_dir)
    write_datamodule_file(m3ae_dir)
    patch_datasets_init(m3ae_dir)
    patch_datamodules_init(m3ae_dir)
    patch_config(m3ae_dir, vqa_label_size)
    return vqa_label_size


def _parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--m3ae-dir", required=True)
    parser.add_argument("--vocab-json", required=True)
    return parser.parse_args()


if __name__ == "__main__":
    args = _parse_args()
    vqa_label_size = apply_patch(args.m3ae_dir, args.vocab_json)
    print(f"Patch aplicado em {args.m3ae_dir}: VQAKVASIRDataset/DataModule criados e "
          f"registrados, task_finetune_vqa_kvasir com vqa_label_size={vqa_label_size}.")
