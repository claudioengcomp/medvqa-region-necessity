def _kvasir_preprocess_cache_path(
    arrow_path: str,
    preprocessor: Callable[[PILImage.Image], PILImage.Image] | None,
) -> str | None:
    """Stable cache path for the result of the Kvasir normalization+preprocessing
    `.map()`.

    Observed finding (campaign of 31/08/2026): `load_condition_dataset` builds the
    dataset via `Dataset.from_dict(...)` (Python lists in memory), which has no
    persistent `cache_files` -- without an explicit `cache_file_name`,
    `datasets.map()` writes to a new temporary file in every process, so the
    3 seeds of each of the 12 training runs of the campaign recomputed
    denoise+CLAHE from scratch (~35-90 min of CPU each, the very same
    transformation -- it is a transformation of the IMAGE, not of the model, and
    it is exactly the same between LoRA/DoRA and between different models).

    Derives a deterministic file name from the source arrow (path + mtime, so it
    invalidates itself if the arrow is rebuilt) and from the exact preprocessor
    configuration (via `repr()` of the `ImagePreprocessor` dataclass, which
    includes all fields) -- any change in either one changes the hash and yields
    a new cache, never serving a stale result by mistake.

    Returns None if `preprocessor` is None (nothing to cache) or if the source
    file does not exist yet (lets `datasets.map()` fall back to the default
    behaviour instead of generating a path based on a non-existent mtime)."""
    if preprocessor is None:
        return None
    if not os.path.exists(arrow_path):
        return None

    key = "|".join([
        os.path.abspath(arrow_path),
        str(os.path.getmtime(arrow_path)),
        repr(preprocessor),
    ])
    digest = hashlib.sha256(key.encode("utf-8")).hexdigest()[:16]
    base = os.path.splitext(os.path.basename(arrow_path))[0]
    os.makedirs(_KVASIR_PREPROCESS_CACHE_DIR, exist_ok=True)
    return f"{_KVASIR_PREPROCESS_CACHE_DIR}/{base}_{digest}.arrow"


def load_dataset_by_enum(
    dataset_enum: med_vlm.enums.DatasetName,
    split: str = "train",
    preprocessor: Callable[[PILImage.Image], PILImage.Image] | None = None,
    drop_image: bool = False,
    arrow_paths: dict | None = None,
):
    """Loads a dataset based on the provided enum value and applies a normalization
    function to it.

    drop_image (v7_txt, 2026-10-09): text-only arm; `image` comes out as None and the
    preprocessing cache (image-only) is not used.

    When ``dataset_enum`` is :attr:`~med_vlm.enums.DatasetName.COMBINED` all four
    individual medical VQA datasets are loaded (with appropriate split fallbacks) and
    concatenated into a single dataset.

    Args:
        dataset_enum: Which dataset (or COMBINED) to load.
        split: Canonical split name – ``"train"``, ``"validation"``, or ``"test"``.
        preprocessor: Optional image preprocessor applied after RGB conversion.
            Pass an :class:`~med_vlm.data.preprocessor.ImagePreprocessor` instance
            to enable CLAHE / denoising.
    """
    if dataset_enum == med_vlm.enums.DatasetName.COMBINED:
        parts = []
        for name in _INDIVIDUAL_DATASETS:
            actual_split = _SPLIT_MAP[name].get(split, split)
            try:
                ds = load_dataset(name.value, split=actual_split)
                parts.append(_normalize(ds, preprocessor=preprocessor))
            except Exception as e:
                import warnings

                warnings.warn(
                    f"Failed to load dataset {name.value!r}"
                    f" (split={actual_split!r}): {e}"
                )
        if not parts:
            raise ValueError(
                f"No datasets could be loaded for COMBINED split='{split}'"
            )
        return concatenate_datasets(parts)

    if drop_image:
        preprocessor = None

    # v7_txt (2026-10-15, VQA-RAD single source): `data.arrows` in the YAML points the split to a local arrow in M3AE format
    # (same reader as Kvasir/HEAL/MIMIC); the dataset enum stays the same, so prompt and rescoring do not change.
    if arrow_paths and split in arrow_paths:
        arrow_path = arrow_paths[split]
        ds = load_condition_dataset(arrow_path)
        cache_file_name = _kvasir_preprocess_cache_path(arrow_path, preprocessor)
        return _normalize(
            ds,
            preprocessor=preprocessor,
            answers_key="answers",
            id_key="id",
            cache_file_name=cache_file_name,
            drop_image=drop_image,
        )   # only touches the image; no image, no preprocessing cache

    if dataset_enum == med_vlm.enums.DatasetName.KVASIR_VQA:
        arrow_path = _KVASIR_CLEAN_ARROW_PATH[split]
        ds = load_condition_dataset(arrow_path)
        cache_file_name = _kvasir_preprocess_cache_path(arrow_path, preprocessor)
        return _normalize(
            ds,
            preprocessor=preprocessor,
            answers_key="answers",
            id_key="id",
            cache_file_name=cache_file_name,
            drop_image=drop_image,
        )

    if dataset_enum == med_vlm.enums.DatasetName.HEAL:
        arrow_path = _HEAL_ARROW_PATH[split]
        ds = load_condition_dataset(arrow_path)
        cache_file_name = _kvasir_preprocess_cache_path(arrow_path, preprocessor)
        return _normalize(
            ds,
            preprocessor=preprocessor,
            answers_key="answers",
            id_key="id",
            cache_file_name=cache_file_name,
            drop_image=drop_image,
        )

    if dataset_enum == med_vlm.enums.DatasetName.MIMIC:
        arrow_path = _MIMIC_ARROW_PATH[split]
        ds = load_condition_dataset(arrow_path)
        cache_file_name = _kvasir_preprocess_cache_path(arrow_path, preprocessor)
        return _normalize(
            ds,
            preprocessor=preprocessor,
            answers_key="answers",
            id_key="id",
            cache_file_name=cache_file_name,
            drop_image=drop_image,
        )

    ds = load_dataset(dataset_enum.value, split=split)
    return _normalize(ds, preprocessor=preprocessor, drop_image=drop_image)
